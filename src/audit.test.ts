import { VOCAB } from '@/content';
import { ALL_KANJI } from '@/content/kanji';
import { ALL_GRAMMAR, ALL_EXERCISES } from '@/content/grammar';
import { WORD_CLASS } from '@/content/wordClass';
import { WORD_RECORDINGS } from '@/content/wordAudio';
import { PITCH } from '@/content/pitch';
import { SENTENCE_BANK } from '@/content/sentenceBank';
import { KANA } from '@/data/kana';
import { strokeModel } from '@/features/writing/model';
import { examplesFor } from '@/features/vocab/wordInfo';
import { findVerb } from '@/features/conjugation/verbs';
import { ALL_ITEMS } from '@/features/catalog';
import { LESSONS } from '@/content/lessons';

it('audit', () => {
  const out: string[] = [];
  const noClass = VOCAB.filter((w) => !WORD_CLASS[`${w.jp}|${w.reading}`] && !findVerb(w.id) && w.group !== 'Verbos' && w.group !== 'Adjetivos');
  out.push(`vocab ${VOCAB.length}; sem classe ${noClass.length}: ${noClass.slice(0, 15).map((w) => w.jp).join(' ')}`);
  const noPitch = VOCAB.filter((w) => !(PITCH as Record<string, unknown>)[`${w.jp}|${w.reading}`]);
  out.push(`sem tom ${noPitch.length}`);
  const noAudio = VOCAB.filter((w) => !WORD_RECORDINGS[w.jp]);
  out.push(`sem áudio nativo ${noAudio.length}`);
  const noSentence = VOCAB.filter((w) => examplesFor(w.id).length === 0);
  out.push(`sem frase no banco ${noSentence.length}: ${noSentence.slice(0, 20).map((w) => w.jp).join(' ')}`);
  const emptyMeaning = VOCAB.filter((w) => !w.meaning || w.meaning.length < 2 || /\?|TODO/.test(w.meaning));
  out.push(`significado vazio/suspeito ${emptyMeaning.length}: ${emptyMeaning.map((w) => w.jp).join(' ')}`);
  const dupMeaning = new Map<string, string[]>();
  for (const w of VOCAB) dupMeaning.set(w.meaning, [...(dupMeaning.get(w.meaning) ?? []), w.jp]);
  const dups = [...dupMeaning.entries()].filter(([, v]) => v.length > 1);
  out.push(`significados repetidos ${dups.length}: ${dups.slice(0, 15).map(([m, v]) => `${m}=${v.join('/')}`).join('; ')}`);
  const noStrokes = ALL_ITEMS.filter((i) => !strokeModel(i.char) && [...i.char].length === 1);
  out.push(`itens de 1 char sem traços ${noStrokes.length}: ${noStrokes.map((i) => i.char).join('')}`);
  const lessonChars = new Set(Object.values(LESSONS).flatMap((l) => l.flatMap((x) => [...x.items])));
  const notInLessons = ALL_ITEMS.filter((i) => !lessonChars.has(i.char));
  out.push(`itens fora de lição ${notInLessons.length}: ${notInLessons.map((i) => i.char).join('')}`);
  const kanjiNoEx = ALL_KANJI.filter((k) => !k.on?.length && !k.kun?.length);
  out.push(`kanji sem leitura ${kanjiNoEx.length}`);
  const topicEx = new Map<string, number>();
  for (const e of ALL_EXERCISES) topicEx.set(e.topic, (topicEx.get(e.topic) ?? 0) + 1);
  const thin = ALL_GRAMMAR.filter((g) => (topicEx.get(g.id) ?? 0) < 2);
  out.push(`tópicos com <2 exercícios de montar ${thin.length}: ${thin.map((g) => g.id).join(' ')}`);
  out.push(`banco ${SENTENCE_BANK.length}; kana ${KANA.length}`);
  console.log('\n' + out.join('\n'));
});
